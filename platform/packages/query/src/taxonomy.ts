/**
 * What things ARE: the item vocabulary search uses to understand listings.
 *
 * Words alone mislead. "All Steel Computer Chair" contains "computer" and is a
 * chair; "Dell Chromebook 5190 Laptop" never says "computer" and is one. So
 * every listing is classified by its head noun, the last item its title names
 * (English puts the thing last: a computer chair is a chair), and a search for
 * "computer" asks for listings whose head is a computer or any kind of one:
 * laptops, desktops, all-in-ones, MacBooks, Chromebooks.
 *
 * This file is the single source. scripts/gen-search-taxonomy.mjs writes it
 * into the database (migration 0046), where classify_listing() tags every lot
 * and search_resolve() reads every query, so the app, search and hunts all
 * read one vocabulary. test/taxonomy.test.ts fails if the two drift.
 *
 * Rules for editing:
 * 1. A term is a word or phrase that NAMES the thing, in the singular. The
 *    database stems both terms and titles ("laptops" is "laptop"), so plurals
 *    come free; irregular ones ("knives", "mice", "shelves") are listed.
 * 2. Prefer a phrase to a bare word whenever the bare word means something
 *    else elsewhere: "computer chair" is a chair, "baby monitor" is not a
 *    screen, "light tower" is not a lamp. The longest phrase always wins.
 * 3. A word that names two things gets `cues`: words that, appearing beside
 *    it, choose that meaning ("router" + "wifi" is a network router). One
 *    meaning is the default; the rest are `fallback`. A query keeps every
 *    meaning its words do not rule out.
 * 4. `related` lists what a buyer of this thing also wants to see, shown below
 *    the exact matches: tablets beside computers, ammunition beside rifles.
 * 5. Brands are not items. They come from lexicon.BRANDS (unambiguous forms
 *    only) and from BRAND_PHRASES here, so "Watch Tower" rifles are rifles.
 * 6. A concept's NAMES (CONCEPT_NAMES, plus its label) stand for all of it; a
 *    query naming it finds every kind ("computer" finds laptops). Any other
 *    term is a narrower kind, and its own words must appear ("socket set"),
 *    except a word that alone names the concept ("laptop" in "gaming laptop").
 *    Where kinds that buyers search for share no words ("gpu", "graphics card",
 *    "video card"), give them a concept of their own instead.
 */

export interface TaxonomyTerm {
  /** The word or phrase. */
  readonly text: string;
  /** Words that select this meaning when they appear in the same title or query. */
  readonly cues?: readonly string[];
  /** Only chosen by a cue; never the meaning of the bare word. */
  readonly fallback?: boolean;
}

export interface ItemConcept {
  readonly id: string;
  /** Plural, as a heading: "Laptops". */
  readonly label: string;
  readonly parent: string | null;
  readonly terms: readonly (string | TaxonomyTerm)[];
  /** Concept ids shown as close matches when this one is searched (rule 4). */
  readonly related?: readonly string[];
}

function k(
  id: string,
  label: string,
  parent: string | null,
  terms: readonly (string | TaxonomyTerm)[],
  related: readonly string[] = [],
): ItemConcept {
  return { id, label, parent, terms, related };
}

/** A term with cue words (rule 3). */
function cue(text: string, cues: readonly string[], fallback = false): TaxonomyTerm {
  return { text, cues, fallback };
}

